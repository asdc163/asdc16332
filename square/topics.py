def pick(index: int) -> Topic:
    """依序輪替，用完再從頭。index 通常是「這是第幾篇教育貼文」。"""
    return TOPICS[index % len(TOPICS)]


def by_id(topic_id: str) -> Topic | None:
    return next((t for t in TOPICS if t.id == topic_id), None)


def coverage_weeks(posts_per_week: int = 3) -> float:
    return len(TOPICS) / posts_per_week
